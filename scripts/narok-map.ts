/**
 * Builds the outline of Narok County for the home page map from geoBoundaries (public domain,
 * RCMRD GeoPortal, 2020 county boundaries).
 *
 * Usage: tsx scripts/narok-map.ts <path to geoBoundaries-KEN-ADM1_simplified.geojson>
 * Source: https://www.geoboundaries.org/api/current/gbOpen/KEN/ADM1/
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

type Position = [number, number]
type Feature = {
  properties: { shapeName: string }
  geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: number[][][] | number[][][][] }
}

// Narok Town, in Ewaso Ng'iro, Narok Town Ward.
const MARKER = { lon: 35.871, lat: -1.078 }
const VIEW_WIDTH = 400

function simplify(points: Position[], tolerance: number): Position[] {
  const first = points[0]
  const last = points[points.length - 1]
  let index = -1
  let max = 0
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i]
    const dx = last[0] - first[0]
    const dy = last[1] - first[1]
    const length = Math.hypot(dx, dy) || 1
    const distance = Math.abs(dy * x - dx * y + last[0] * first[1] - last[1] * first[0]) / length
    if (distance > max) {
      max = distance
      index = i
    }
  }
  if (max <= tolerance || index < 0) return [first, last]
  return [
    ...simplify(points.slice(0, index + 1), tolerance).slice(0, -1),
    ...simplify(points.slice(index), tolerance),
  ]
}

async function main(): Promise<void> {
  const source = process.argv[2]
  if (!source) throw new Error('Pass the path to the geoBoundaries GeoJSON file')
  const collection = JSON.parse(await readFile(source, 'utf8')) as { features: Feature[] }
  const narok = collection.features.find((f) => f.properties.shapeName === 'Narok')
  if (!narok) throw new Error('Narok not found in the GeoJSON')

  const rings =
    narok.geometry.type === 'Polygon'
      ? [(narok.geometry.coordinates as number[][][])[0]]
      : (narok.geometry.coordinates as number[][][][]).map((polygon) => polygon[0])
  const outer = rings.sort((a, b) => b.length - a.length)[0] as Position[]

  // Equirectangular projection, with longitude scaled by the cosine of the middle latitude.
  const lats = outer.map((p) => p[1])
  const lons = outer.map((p) => p[0])
  const midLat = (Math.min(...lats) + Math.max(...lats)) / 2
  const k = Math.cos((midLat * Math.PI) / 180)
  const project = ([lon, lat]: Position): Position => [lon * k, -lat]
  const projected = outer.map(project)
  // The ring starts and ends at the same point, so split it at the farthest vertex first.
  const start = projected[0]
  const far = projected.reduce(
    (best, p, i) =>
      Math.hypot(p[0] - start[0], p[1] - start[1]) > best.d
        ? { i, d: Math.hypot(p[0] - start[0], p[1] - start[1]) }
        : best,
    { i: 0, d: 0 },
  ).i
  const simple = [
    ...simplify(projected.slice(0, far + 1), 0.004).slice(0, -1),
    ...simplify(projected.slice(far), 0.004),
  ]

  const xs = simple.map((p) => p[0])
  const ys = simple.map((p) => p[1])
  const minX = Math.min(...xs)
  const minY = Math.min(...ys)
  const scale = (VIEW_WIDTH - 20) / (Math.max(...xs) - minX)
  const toView = ([x, y]: Position): Position => [10 + (x - minX) * scale, 10 + (y - minY) * scale]
  const view = simple.map(toView)
  const height = Math.ceil(Math.max(...view.map((p) => p[1])) + 10)

  const d = `${view.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${x.toFixed(1)} ${y.toFixed(1)}`).join(' ')} Z`
  const [mx, my] = toView(project([MARKER.lon, MARKER.lat]))

  const file = path.join(process.cwd(), 'src', 'components', 'sections', 'narok-map.generated.ts')
  await writeFile(
    file,
    `// Generated by scripts/narok-map.ts from geoBoundaries (public domain, RCMRD GeoPortal 2020).\n` +
      `export const narokOutline = '${d}'\n` +
      `export const narokMarker = { x: ${mx.toFixed(1)}, y: ${my.toFixed(1)} }\n` +
      `export const narokViewBox = '0 0 ${VIEW_WIDTH} ${height}'\n`,
  )
  console.log(
    `Wrote ${file}: ${view.length} points, bounds lon ${Math.min(...lons).toFixed(2)}..${Math.max(...lons).toFixed(2)}`,
  )
}

main().catch((error: unknown) => {
  console.error(error)
  process.exit(1)
})
