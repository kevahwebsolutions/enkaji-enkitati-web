const ISO_DATE = /^\d{4}-\d{2}-\d{2}T/

function normalise(value: unknown, insideArray = false): unknown {
  if (value === undefined || value === null || value === '') return undefined
  if (Array.isArray(value)) {
    return value.length === 0 ? undefined : value.map((item) => normalise(item, true))
  }
  if (typeof value === 'string' && ISO_DATE.test(value)) {
    const time = new Date(value).getTime()
    return Number.isNaN(time) ? value : time
  }
  if (value && typeof value === 'object') {
    const record = value as Record<string, unknown>
    // A populated relationship compares by id.
    if ('id' in record && 'createdAt' in record) return record.id
    const entries = Object.keys(record)
      .sort()
      // Row ids are generated by Payload, so they never appear in seed data.
      .filter((key) => !(insideArray && key === 'id'))
      .map((key) => [key, normalise(record[key])] as const)
      .filter(([, v]) => v !== undefined)
    return Object.fromEntries(entries)
  }
  return value
}

export const sameValue = (a: unknown, b: unknown): boolean =>
  JSON.stringify(normalise(a)) === JSON.stringify(normalise(b))

/** True when every key in `seed` already holds the same value in `existing`. */
export function containsSeed(
  existing: Record<string, unknown>,
  seed: Record<string, unknown>,
): boolean {
  return Object.keys(seed).every((key) => sameValue(existing[key], seed[key]))
}
